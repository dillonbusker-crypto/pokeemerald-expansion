#!/usr/bin/env python3
# Eight Gauntlets: writes src/data/facility_shop_tiers.h, the Showdown singles
# tier of every Pokemon the shop sells (shop-spec.md, "The Pokemon menu").
#
# Run from the repo root:  python3 tools/showdown_tiers.py
# It downloads Showdown's tier files, so rerun it whenever Smogon reshuffles
# the tiers, then rebuild. Pass a folder holding formats-data.ts and
# gen8/gen7/gen6-formats-data.ts to use local copies instead.
#
# A Pokemon takes its Gen 9 tier; one not in Scarlet/Violet ("Illegal") takes
# its tier from the last generation it was legal in. BL tiers fold into the
# tier above, and PU and below become Low Tier: PU and ZUBL as its
# Competitive list (SHOWDOWN_TIER_PU), ZU, NFE and LC as its Other list
# (SHOWDOWN_TIER_LOW).

import collections, datetime, os, re, sys, urllib.request

URL = 'https://raw.githubusercontent.com/smogon/pokemon-showdown/master/data/'
FILES = [('9', 'formats-data.ts'), ('8', 'mods/gen8/formats-data.ts'),
         ('7', 'mods/gen7/formats-data.ts'), ('6', 'mods/gen6/formats-data.ts')]
OUT = 'src/data/facility_shop_tiers.h'

BUCKETS = {
    'Uber': 'UBER', 'AG': 'UBER',
    'OU': 'OU', 'UUBL': 'OU',
    'UU': 'UU', 'RUBL': 'UU',
    'RU': 'RU', 'NUBL': 'RU',
    'NU': 'NU', 'PUBL': 'NU',
    'PU': 'PU', 'ZUBL': 'PU',
    'ZU': 'LOW', 'NFE': 'LOW', 'LC': 'LOW',
}

# Never had a Showdown tier.
OVERRIDES = {'SPECIES_FLOETTE_ETERNAL': 'OU'}

# Form suffixes on our constants that Showdown leaves off (its default forms)
# or spells differently.
SUFFIXES = [('_GALAR_STANDARD', 'galar'), ('_SINGLE_STRIKE', ''), ('_INCARNATE', ''),
            ('_UNREMARKABLE', ''), ('_DISGUISED', ''), ('_CONFINED', ''), ('_ORDINARY', ''),
            ('_OVERCAST', ''), ('_STANDARD', ''), ('_MIDDAY', ''), ('_SHIELD', ''),
            ('_NORMAL', ''), ('_SPRING', ''), ('_PHONY', ''), ('_THREE', ''), ('_AMPED', ''),
            ('_CURLY', ''), ('_WEST', ''), ('_ARIA', ''), ('_LAND', ''), ('_TEAL', ''),
            ('_ZERO', ''), ('_RED', ''), ('_50', ''), ('_M', '')]


def read_showdown(src, path):
    if src:
        text = open(os.path.join(src, path.replace('mods/', '').replace('/', '-'))).read()
    else:
        text = urllib.request.urlopen(URL + path, timeout=60).read().decode()
    data, cur = {}, None
    for line in text.splitlines():
        m = re.match(r'^\t(\w+): \{', line)
        if m:
            cur = data.setdefault(m.group(1), {})
            continue
        m = re.match(r'^\t\ttier: "([^"]*)"', line)
        if m and cur is not None:
            cur['tier'] = m.group(1)
    return data


def showdown_id(species, aliases):
    name = aliases.get(species, species)[len('SPECIES_'):]
    for suffix, repl in SUFFIXES:
        if name.endswith(suffix):
            name = name[:-len(suffix)] + repl
            break
    return re.sub(r'[^a-z0-9]', '', name.lower())


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else None
    gens = [(g, read_showdown(src, p)) for g, p in FILES]
    aliases = dict(re.findall(r'(SPECIES_\w+)\s*=\s*(SPECIES_\w+),',
                              open('include/constants/species.h').read()))
    shop = open('src/facility_shop.c').read()
    species = []
    for m in re.finditer(r'\{ (SPECIES_\w+),\s*\d+,\s*\d+ \}', shop):
        if m.group(1) not in species:
            species.append(m.group(1))

    rows, errors, counts = [], [], collections.Counter()
    for s in species:
        if s in OVERRIDES:
            bucket, why = OVERRIDES[s], 'set by hand'
        else:
            sid, tier, gen = showdown_id(s, aliases), None, None
            for g, data in gens:
                t = data.get(sid, {}).get('tier')
                if t and t != 'Illegal':
                    tier, gen = t.strip('()'), g
                    break
            if tier is None or tier not in BUCKETS:
                errors.append(f'{s} ({sid}): no usable tier ({tier})')
                continue
            bucket, why = BUCKETS[tier], f'Gen {gen} {tier}'
        counts[bucket] += 1
        rows.append(f'    [{s}] = SHOWDOWN_TIER_{bucket}, // {why}')

    if errors:
        sys.exit('\n'.join(errors))
    with open(OUT, 'w') as f:
        f.write('// Generated by tools/showdown_tiers.py on '
                f'{datetime.date.today()}: do not edit by hand, rerun it.\n'
                '// Showdown singles tier of every shop Pokemon (shop-spec.md).\n\n'
                'static const u8 sShowdownTiers[NUM_SPECIES] =\n{\n')
        f.write('\n'.join(rows) + '\n};\n')
    order = ['UBER', 'OU', 'UU', 'RU', 'NU', 'PU', 'LOW']
    print(f'{len(rows)} Pokemon written to {OUT}: ' +
          ', '.join(f'{b} {counts[b]}' for b in order))


if __name__ == '__main__':
    main()
